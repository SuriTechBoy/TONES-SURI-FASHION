# RESPONSE QUALITY GUARD
# ============================================================

def is_invalid_customer_response(response: str) -> bool:
    """
    Detect obvious internal classifications, internal metadata,
    or other responses that must never reach the customer.
    """

    if not response:
        return True

    text = response.strip().lower()

    # --------------------------------------------------------
    # INTERNAL CLASSIFICATION PATTERNS
    # --------------------------------------------------------

    forbidden_patterns = [
        "user safety:",
        "safety classification",
        "safety status:",
        "moderation result",
        "moderation classification",
        "moderation status:",
        "internal classification",
        "internal status:",
        "risk classification",
        "risk status:",
        "policy classification:",
        "classification:",
    ]

    for pattern in forbidden_patterns:

        if pattern in text:
            return True

    # --------------------------------------------------------
    # INTERNAL SYSTEM INFORMATION
    # --------------------------------------------------------

    internal_terms = [
        "retrieval score",
        "knowledge id",
        "vector database",
        "vector db",
        "rag pipeline",
        "internal knowledge base",
        "routing logic",
        "system prompt",
        "retrieval system",
        "internal metadata",
    ]

    for term in internal_terms:

        if term in text:
            return True

    # --------------------------------------------------------
    # INTERNAL PRODUCT / KNOWLEDGE IDS
    # --------------------------------------------------------

    if re.search(
        r"tones-prod-[a-z0-9_-]+",
        text,
        re.IGNORECASE,
    ):
        return True

    if re.search(
        r"tones-kb-[a-z0-9_-]+",
        text,
        re.IGNORECASE,
    ):
        return True

    return False


