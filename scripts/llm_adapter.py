"""
TONES Fashion - LLM Adapter

Purpose:
    Convert retrieved RAG context into a customer-facing answer.

Providers:
    - mock
    - openrouter

Architecture:

    Customer Query
          ↓
    RAG Context Builder
          ↓
    RAG Prompt
          ↓
    LLM Adapter
          ↓
    OpenRouter
          ↓
    Selected Model
          ↓
    Response Quality Guard
          ↓
    Customer Answer
"""

import os
import re
import requests
from abc import ABC, abstractmethod


# ============================================================
# BASE LLM ADAPTER
# ============================================================

class LLMAdapter(ABC):
    """
    Provider-independent interface.
    """

    @abstractmethod
    def generate(
        self,
        system_prompt: str,
        user_prompt: str,
    ) -> str:
        """
        Generate a response from the LLM.
        """
        raise NotImplementedError


