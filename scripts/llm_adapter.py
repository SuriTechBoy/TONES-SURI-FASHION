CORRECTION_INSTRUCTION = """

IMPORTANT RESPONSE CORRECTION:

Your previous response was not a valid customer-facing answer.

Answer the customer's actual question now.

Return ONLY the natural customer-facing answer.

Do not output:
- safety classifications
- moderation classifications
- internal classifications
- internal statuses
- routing information
- retrieval information
- knowledge IDs
- product IDs
- reasoning
- implementation details

If the customer asks a normal product or policy question,
answer that question directly using only the supplied knowledge.

If information is unverified, clearly say that it is unverified.

If the question has multiple parts, answer all supported parts.

Do not invent information.

Return only the final customer-facing answer.
"""


