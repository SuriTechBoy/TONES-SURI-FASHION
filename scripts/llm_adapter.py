EMPTY_RESPONSE_RETRY_INSTRUCTION = """

The previous model response was empty.

Please answer the customer's actual question now.

Return ONLY the final customer-facing answer.

Do not return:
- an empty response
- internal classifications
- safety labels
- moderation labels
- routing information
- retrieval information
- knowledge IDs
- product IDs
- reasoning
- analysis

Use only the supplied TONES Fashion information.
"""


