# LLM SERVICE
# ============================================================

class LLMService:
    """
    Main service used by the application.

    The rest of the project interacts with this service
    instead of directly depending on a provider.
    """

    def __init__(
        self,
        adapter: LLMAdapter,
    ):

        self.adapter = adapter

    def answer(
        self,
        system_prompt: str,
        user_prompt: str,
    ) -> str:

        if not system_prompt.strip():

            raise ValueError(
                "System prompt cannot be empty."
            )

        if not user_prompt.strip():

            raise ValueError(
                "User prompt cannot be empty."
            )

        # ====================================================
        # FIRST REQUEST
        # ====================================================

        try:

            response = self.adapter.generate(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
            )

        except RuntimeError as exc:

            error_text = str(exc).lower()

            # Retry only for an empty OpenRouter response.
            if "empty response" not in error_text:
                raise

            response = None

        # ====================================================
        # EMPTY RESPONSE RETRY
        # ====================================================

        if not response:

            retry_user_prompt = (
                user_prompt
                + "\n\n"
                + EMPTY_RESPONSE_RETRY_INSTRUCTION
            )

            response = self.adapter.generate(
                system_prompt=system_prompt,
                user_prompt=retry_user_prompt,
            )

        # ====================================================
        # FINAL EMPTY CHECK
        # ====================================================

        if not response or not response.strip():

            raise RuntimeError(
                "LLM returned an empty response after retry."
            )

        response = response.strip()

        # ====================================================
        # FIRST RESPONSE QUALITY CHECK
        # ====================================================

        if not is_invalid_customer_response(
            response
        ):

            return response

        # ====================================================
        # INVALID RESPONSE CORRECTION
        # ====================================================

        corrected_user_prompt = (
            user_prompt
            + "\n\n"
            + CORRECTION_INSTRUCTION
        )

        corrected_response = self.adapter.generate(
            system_prompt=system_prompt,
            user_prompt=corrected_user_prompt,
        )

        # ====================================================
        # CORRECTION RESPONSE EMPTY CHECK
        # ====================================================

        if not corrected_response:

            raise RuntimeError(
                "LLM returned an empty response "
                "after correction retry."
            )

        corrected_response = corrected_response.strip()

        # ====================================================
        # FINAL QUALITY CHECK
        # ====================================================

        if is_invalid_customer_response(
            corrected_response
        ):

            raise RuntimeError(
                "LLM returned an invalid internal-style "
                "response after the correction retry."
            )

        return corrected_response


# ============================================================
# SERVICE FACTORY
# ============================================================

def get_llm_service(
    provider: str | None = None,
) -> LLMService:
    """
    Create the requested LLM service.

    Provider can be supplied directly or through:
        TONES_LLM_PROVIDER

    Supported:
        mock
        openrouter
    """

    selected_provider = (
        provider
        or os.getenv(
            "TONES_LLM_PROVIDER",
            "mock",
        )
    ).lower().strip()

    if selected_provider == "mock":

        return LLMService(
            MockLLMAdapter()
        )

    if selected_provider == "openrouter":

        return LLMService(
            OpenRouterLLMAdapter()
        )

    raise ValueError(
        f"Unsupported LLM provider: {selected_provider}"
    )


