class OpenRouterLLMAdapter(LLMAdapter):
    """
    OpenRouter implementation of the LLM adapter.

    Environment variables:
        OPENROUTER_API_KEY
        OPENROUTER_MODEL

    Default model:
        openrouter/free
    """

    BASE_URL = "https://openrouter.ai/api/v1/chat/completions"

    def __init__(self):

        self.api_key = os.getenv(
            "OPENROUTER_API_KEY"
        )

        if not self.api_key:
            raise RuntimeError(
                "OPENROUTER_API_KEY environment variable is not set."
            )

        self.model = os.getenv(
            "OPENROUTER_MODEL",
            "openrouter/free",
        )

        self.timeout = int(
            os.getenv(
                "OPENROUTER_TIMEOUT",
                "60",
            )
        )

    def generate(
        self,
        system_prompt: str,
        user_prompt: str,
    ) -> str:

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        payload = {
            "model": self.model,
            "messages": [
                {
                    "role": "system",
                    "content": system_prompt,
                },
                {
                    "role": "user",
                    "content": user_prompt,
                },
            ],
            "temperature": 0.2,
            "max_tokens": 800,
        }

        try:

            response = requests.post(
                self.BASE_URL,
                headers=headers,
                json=payload,
                timeout=self.timeout,
            )

        except requests.RequestException as exc:

            raise RuntimeError(
                f"OpenRouter request failed: {exc}"
            ) from exc

        if response.status_code != 200:

            try:
                error_data = response.json()

            except ValueError:
                error_data = response.text

            raise RuntimeError(
                "OpenRouter API request failed.\n"
                f"HTTP Status: {response.status_code}\n"
                f"Response: {error_data}"
            )

        try:

            data = response.json()

        except ValueError as exc:

            raise RuntimeError(
                "OpenRouter returned an invalid JSON response."
            ) from exc

        try:

            content = data["choices"][0]["message"]["content"]

        except (
            KeyError,
            IndexError,
            TypeError,
        ) as exc:

            raise RuntimeError(
                "OpenRouter response did not contain "
                "the expected assistant message."
            ) from exc

        if not content or not content.strip():

            raise RuntimeError(
                "OpenRouter returned an empty response."
            )

        return content.strip()


